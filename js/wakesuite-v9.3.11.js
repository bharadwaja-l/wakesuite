  function replaceWordText(xml,replacements){
    const doc=new DOMParser().parseFromString(xml,'application/xml');
    if(doc.getElementsByTagName('parsererror').length)throw new Error('POA template XML is invalid.');
    const ns='http://schemas.openxmlformats.org/wordprocessingml/2006/main';
    const counts=replacements.map(()=>0);
    // Paragraph boundaries prevent matching unrelated adjacent text; run styles stay in place.
    for(const paragraph of [...doc.getElementsByTagNameNS(ns,'p')]){
      const nodes=[...paragraph.getElementsByTagNameNS(ns,'t')];
      replacements.forEach(([from,to],k)=>{
        const joined=nodes.map(n=>n.textContent).join('');
        const hits=[];let pos=0;while(from&&(pos=joined.indexOf(from,pos))>=0){hits.push(pos);pos+=from.length;}
        for(const begin of hits.reverse()){
          let cursor=0,inserted=false;
          for(const node of nodes){const text=node.textContent,start=cursor,end=cursor+text.length;cursor=end;
            if(end<=begin||start>=begin+from.length)continue;
            const lo=Math.max(0,begin-start),hi=Math.min(text.length,begin+from.length-start);
            node.textContent=text.slice(0,lo)+(inserted?'':to)+text.slice(hi);node.setAttribute('xml:space','preserve');inserted=true;
          }counts[k]++;
        }
      });
    }
    return {xml:new XMLSerializer().serializeToString(doc),counts};
  }


  async function buildPoaDocx(category,asin,title){
    const cfg=POA_CONFIG.templates[category];
    if(!cfg)throw new Error(`No POA master template is configured for category: ${category||'Unmapped'}.`);
    if(!asin)throw new Error('POA cannot be generated without an ASIN.');
    if(!title)throw new Error(`POA cannot be generated for ${asin}: Amazon product title is unavailable.`);
    const JSZip=await loadJsZip();
    if(!templateBuffers.has(cfg.asset)){const response=await fetch(cfg.asset);if(!response.ok)throw new Error(`POA master template could not be loaded for ${category}.`);templateBuffers.set(cfg.asset,await response.arrayBuffer());}
    const zip=await JSZip.loadAsync(templateBuffers.get(cfg.asset).slice(0));
    const sampleTitleXml=xmlEscape(cfg.sampleTitle),newTitleXml=xmlEscape(title);
    const xmlFiles=Object.keys(zip.files).filter(name=>/^word\/.+\.xml$/i.test(name));
    let asinReplacements=0,titleReplacements=0;
    for(const name of xmlFiles){
      const file=zip.file(name); if(!file)continue;
      let xml=await file.async('string');
      const before=xml;
      const result=replaceWordText(xml,[[cfg.sampleAsin,asin],[cfg.sampleTitle,title]]);
      xml=result.xml;asinReplacements+=result.counts[0];titleReplacements+=result.counts[1];
      if(xml!==before)zip.file(name,xml);
    }
    if(!asinReplacements)throw new Error(`POA template validation failed: sample ASIN was not found in the ${category} template.`);
    if(!titleReplacements)throw new Error(`POA template validation failed: sample product title was not found in the ${category} template.`);
    return zip.generateAsync({type:'blob',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',compression:'DEFLATE'});
  }

