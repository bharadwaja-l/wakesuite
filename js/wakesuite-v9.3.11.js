  function mimeTypeFor(name){
    const n=String(name||'').toLowerCase();
    if(n.endsWith('.docx'))return 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
    if(n.endsWith('.xlsx'))return 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
    return 'application/octet-stream';
  }
  function buildMimeMulti({to,cc=[],bcc=[],subject,html,attachments=[]}){
    const boundary=`WakeSuite9311_${Date.now()}_${Math.random().toString(36).slice(2)}`;
    const headers=[`To: ${to.join(', ')}`,cc.length?`Cc: ${cc.join(', ')}`:'',bcc.length?`Bcc: ${bcc.join(', ')}`:'',`Subject: ${v4MimeSubject(subject)}`,'MIME-Version: 1.0',`Content-Type: multipart/mixed; boundary="${boundary}"`].filter(Boolean).join('\r\n');
    let body=`${headers}\r\n\r\n--${boundary}\r\nContent-Type: text/html; charset="UTF-8"\r\nContent-Transfer-Encoding: base64\r\n\r\n${v4Utf8Base64(html)}\r\n`;
    for(const a of attachments||[]){
      if(!a?.name||!a?.bytes)continue;
      body+=`--${boundary}\r\nContent-Type: ${mimeTypeFor(a.name)}; name="${a.name}"\r\nContent-Disposition: attachment; filename="${a.name}"\r\nContent-Transfer-Encoding: base64\r\n\r\n${v4BytesToBase64(a.bytes)}\r\n`;
    }
    body+=`--${boundary}--`;
    return v4Base64Url(v4Utf8Base64(body));
  }
  async function gmailDeliver({mode='send',to,cc=[],bcc=[],subject,html,attachments=[]}){
    const token=await v4GetGmailToken();
    const actual=window.WakeSuiteRelease.clock();
    subject=subject.replace(/ \| \d{2}:\d{2} (?:AM|PM)$/,'')+` | ${actual}`;
    attachments=attachments.map(a=>({...a,name:window.WakeSuiteRelease.stampedName(a.name.replace(/_\d{2}-\d{2}-(?:AM|PM)(?=\.[^.]+$)/,''),actual)}));
    const raw=buildMimeMulti({to,cc,bcc,subject,html,attachments});
    const endpoint=mode==='draft'?'https://gmail.googleapis.com/gmail/v1/users/me/drafts':'https://gmail.googleapis.com/gmail/v1/users/me/messages/send';
    const response=await fetch(endpoint,{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify(mode==='draft'?{message:{raw}}:{raw})});
    const data=await response.json().catch(()=>({}));
    if(!response.ok)throw new Error(data?.error?.message||`Gmail API error ${response.status}`);
    return {...data,wakeSuiteDelivery:{subject,time:actual,attachmentNames:attachments.map(a=>a.name)}};
  }

